#!/usr/bin/env python3
"""e168_pick.py 합성 시험: 가장 작은 충족 W 선택, 경계(보상 창 10%·결정 90% 정확, [사전] ±0.002), 미충족(없음), 연결 줄 없음, 결측, 원 로그 파싱.
실행: python3 scripts/test_e168_pick.py (저장소 루트에서)"""
import contextlib
import io
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import e168_pick as P


def C(spec):
    """spec[W] = (결정, 보상 창 보상, [사전] 1e-4, 연결 줄)."""
    return {w: {"dec": d, "rew": r, "pun": 0.01, "nrew": 40, "w": float(w), "pre": p, "post": -800, "conn": c} for w, (d, r, p, c) in spec.items()}


base = {0: (0.050, 0.020, 228, 0)}
ok_all = True


def chk(name, spec, want):
    global ok_all
    sel, _ = P.pick(C({**base, **spec}))   # 시험 구성 수정(첫 판: 정수 키를 dict(**) 로 넘겨 TypeError — 판정 코드와 무관)
    good = sel == want
    ok_all &= good
    print("%-40s 기대 %-5s → %-5s %s" % (name, want, sel, "✓" if good else "✗"))


chk("W5 가 처음 충족", {2: (0.050, 0.005, 228, 1), 5: (0.049, 0.001, 228, 1), 10: (0.048, 0.0, 228, 1), 20: (0.040, 0.0, 228, 1)}, 5)
chk("W2 충족(가장 작음)", {2: (0.050, 0.001, 228, 1), 5: (0.049, 0.0, 228, 1), 10: (0.048, 0.0, 228, 1), 20: (0.04, 0.0, 228, 1)}, 2)
chk("보상 창 10% 정확 → 충족", {2: (0.050, 0.002, 228, 1), 5: (0.05, 0.0, 228, 1), 10: (0.05, 0.0, 228, 1), 20: (0.05, 0.0, 228, 1)}, 2)
chk("보상 창 10.05% → 미충족 → W5", {2: (0.050, 0.00201, 228, 1), 5: (0.05, 0.0, 228, 1), 10: (0.05, 0.0, 228, 1), 20: (0.05, 0.0, 228, 1)}, 5)
chk("결정 90% 정확 → 충족", {2: (0.045, 0.0, 228, 1), 5: (0.04, 0.0, 228, 1), 10: (0.04, 0.0, 228, 1), 20: (0.04, 0.0, 228, 1)}, 2)
chk("결정 89.8% → 미충족 → 없음", {2: (0.0449, 0.0, 228, 1), 5: (0.04, 0.0, 228, 1), 10: (0.03, 0.0, 228, 1), 20: (0.02, 0.0, 228, 1)}, None)
chk("[사전] 차 +20 → 충족", {2: (0.05, 0.0, 248, 1), 5: (0.05, 0.0, 228, 1), 10: (0.05, 0.0, 228, 1), 20: (0.05, 0.0, 228, 1)}, 2)
chk("[사전] 차 +21 → 미충족 → W5", {2: (0.05, 0.0, 249, 1), 5: (0.05, 0.0, 228, 1), 10: (0.05, 0.0, 228, 1), 20: (0.05, 0.0, 228, 1)}, 5)
chk("연결 줄 없음 → 미충족", {2: (0.05, 0.0, 228, 0), 5: (0.05, 0.0, 228, 0), 10: (0.05, 0.0, 228, 0), 20: (0.05, 0.0, 228, 0)}, None)
chk("모두 보상 창 못 막음 → 없음", {2: (0.05, 0.015, 228, 1), 5: (0.05, 0.010, 228, 1), 10: (0.05, 0.005, 228, 1), 20: (0.05, 0.003, 228, 1)}, None)
chk("W2 결측 → W5", {5: (0.05, 0.0, 228, 1), 10: (0.05, 0.0, 228, 1), 20: (0.05, 0.0, 228, 1)}, 5)

with tempfile.TemporaryDirectory() as td:
    os.makedirs(os.path.join(td, "logs", "E168", "calib"))
    w = lambda n, s: open(os.path.join(td, "logs", "E168", "calib", n), "w", encoding="utf-8").write(s)
    line = lambda d, r, wv: ("[E168 KC 발화] 결정 단계(3처리 끝) 평균 %.6f n=100 | 보상 창 보상 시행 평균 %.6f n=40 | 보상 창 처벌 시행 평균 0.010000 n=60 | da_kc_inh=%.2f p=0.20\n" % (d, r, wv))
    w("W0_b15.log", "[사전] x | **변조폭 +0.0228** (y)\n" + line(0.05, 0.02, 0) + "[사후] x | **변조폭 -0.0820**\n")
    for wv, (d, r) in ((2, (0.05, 0.004)), (5, (0.049, 0.0015)), (10, (0.03, 0.0)), (20, (0.02, 0.0))):
        w("W%d_b15.log" % wv, "  [E168 도파민→KC억제] 도파민 뉴런 100 → KC 억제 뉴런 좌·우 400, w=%.2f, p=0.20\n[사전] x | **변조폭 +0.0228** (y)\n" % wv
          + line(d, r, wv) + "[사후] x | **변조폭 -0.2000**\n")
    P.EXP = td
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        P.main()
    out = buf.getvalue()
    pk = open(os.path.join(td, "logs", "E168", "pick.txt"), encoding="utf-8").read().strip()
g = pk == "W=5" and "W* = 5" in out
ok_all &= g
print("%-40s → %s %s" % ("원 로그 파싱·pick.txt", pk, "✓" if g else "✗\n" + out))
print("전체: %s" % ("통과" if ok_all else "실패"))
sys.exit(0 if ok_all else 1)
